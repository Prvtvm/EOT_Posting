//Reading excel data and convert inot JSON to post into IOT
async function Excel_JSON(accessToken,workbook,worksheet) {

    let jsonData = [];   // Initialize an empty array to store JSON data    
    workbook.eachSheet((worksheet) => {
        worksheet.eachRow((row, rowNumber) => {
            if (rowNumber !== 1) { // Skip the header row
                const rowData = {};
                row.eachCell((cell, colNumber) => {                    
                    rowData[worksheet.getCell(1, colNumber).value] = cell.value;
                });
                jsonData.push(rowData);   
            }
         });
    });

    /* Posting json data to IOT */
    const requestBody = {
        Tags: {
            objectId: "E_20024003",
            CategoryId: "M",
            Position: "P_3a9aa01d12db411fb3b6088e5623faf5"
        },
        Values: jsonData
    };
    const response = await axios.post(postUrl, requestBody, {
        headers: {
            'Authorization': `Bearer ${accessToken}`,
            'Content-Type': 'application/json'
        }
    });
    console.log("Data posted successfully...");
}
